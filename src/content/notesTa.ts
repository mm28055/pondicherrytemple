/** An occasion, or several joined by commas: what each is, then "Day 6" and
    the tithi if it has them. Left in English if any part has no Tamil here. */
export function occasionTa(english: string): string {
  // (its commas and semicolons kept)
  const pieces = english.trim().split(/\s*([,;])\s+/);
  const parts = pieces.map((part, i) => {
    if (i % 2) return part;
    if (OCCASIONS[part]) return OCCASIONS[part];
    const n = part.match(/^Navaratri (\w+)$/);
    if (n && TITHIS[n[1]]) return `நவராத்திரி ${TITHIS[n[1]]}`;
    const m = part.match(/^(.*?)(?: Day (\d+))?(?:: (\w+))?$/);
    const name = m && OCCASIONS[m[1]];
    if (!m || !name || (m[3] && !TITHIS[m[3]])) return wordsTa(part) ?? (said(part) !== part ? said(part) : null);
    return `${name}${m[2] ? ` ${m[2]}ஆம் நாள்` : ""}${m[3] ? `: ${TITHIS[m[3]]}` : ""}`;
  });
  return parts.some((p) => p === null) ? said(english) : parts.map((p, i) => (i % 2 ? `${p} ` : p)).join("");
}

