/** The beginnings of a word's Tamil forms, as it may stand in a text: its name
    less the sign its endings replace (…ம், …ு, or the dot of a last letter);
    or, where the third has the name itself in it, the third alone. */
export const beginningsOf = ([name, , also]: DictionaryTa): string[] => {
  const start = name.replace(/ம்$|ு$|்$/, "");
  return also?.some((a) => a.includes(start)) ? also : [start, ...(also ?? [])];
};
